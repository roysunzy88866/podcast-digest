// 「死链」类闸门失败的**精确白名单**(gate-all --deploy 部署模式只放行这几类:链到缺页、纯装饰,
// 既非失真也不影响阅读)。刻意用**精确 Set**而非 startsWith 前缀匹配(GLM 20260831-008[1][2]):
//   · 前缀匹配会让未来任何以「死链」开头的**非装饰性**新 kind(如假想的「死链-失真」)被误放行;
//   · 关联层若日后新增非死链失败类型,也绝不能被 --deploy 静默放过。
// 放行范围一旦要扩,必须在这里显式加 kind 并配测试——白名单是「宁可漏放、不可误放」的安全边界。
export const DEAD_LINK_KINDS = new Set([
  "死链", // 实体层:[[x]] 链到既非集 id 也非实体页
  "死链-块", // 实体层:![[x#^blk]] 块引用目标缺失
  "相关单集死链", // 关联层:相关集无 samples 页,点了跳空
]);

/** 这条失败是否「死链」类(部署模式可放行的唯一一类)。非白名单一律当真失败,不放行。 */
export function isDeadLinkKind(kind) {
  return DEAD_LINK_KINDS.has(String(kind));
}
